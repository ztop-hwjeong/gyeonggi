from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    DateTime,
    FetchedValue,
    Integer,
    MetaData,
    String,
    Table,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID

metadata = MetaData()

analysis_reports = Table(
    "analysis_reports",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("target_id", UUID(as_uuid=True)),
    Column("target_kind", String),
    Column("title", String),
    Column("description", String),
    Column("relevance_criteria", String),
    Column("keywords_override", JSONB),
    Column("is_default", Boolean),
    Column("start_at", DateTime(timezone=True)),
    Column("end_at", DateTime(timezone=True)),
    Column("version", Integer),
    Column("created_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True)),
    schema="ops",
)
report_relevance_runs = Table(
    "report_relevance_runs",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True, server_default=FetchedValue()),
    Column("batch_id", UUID(as_uuid=True)),
    Column("report_id", UUID(as_uuid=True)),
    Column("article_id", UUID(as_uuid=True)),
    Column("content_id", BigInteger),
    Column("content_hash", String),
    Column("title", String),
    Column("criteria", String),
    Column("criteria_hash", String),
    Column("model", String),
    Column("prompt", String),
    Column("prompt_hash", String),
    Column("status", String),
    Column("relevance", String),
    Column("reason", String),
    Column("evidence", JSONB),
    Column("usage", JSONB),
    Column("error", String),
    Column("flow_run_id", UUID(as_uuid=True)),
    Column("submission_attempts", Integer),
    Column("lease_expires_at", DateTime(timezone=True)),
    Column("created_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True)),
    schema="ops",
)
analysis_report_decisions = Table(
    "analysis_report_decisions",
    metadata,
    Column("report_id", UUID(as_uuid=True), primary_key=True),
    Column("article_id", UUID(as_uuid=True), primary_key=True),
    Column("decision", String),
    Column("reason", String),
    Column("created_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True)),
    schema="ops",
)
analysis_report_decision_history = Table(
    "analysis_report_decision_history",
    metadata,
    Column("id", BigInteger, primary_key=True),
    Column("report_id", UUID(as_uuid=True)),
    Column("article_id", UUID(as_uuid=True)),
    Column("previous_decision", String),
    Column("action", String),
    Column("reason", String),
    Column("created_at", DateTime(timezone=True)),
    schema="ops",
)
