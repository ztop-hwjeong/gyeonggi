from sqlalchemy import BigInteger, Boolean, Column, DateTime, MetaData, String, Table
from sqlalchemy.dialects.postgresql import JSONB, UUID

metadata = MetaData()

topics = Table(
    "analysis_topics",
    metadata,
    Column("id", String, primary_key=True),
    Column("name", String),
    Column("description", String),
    Column("synonyms", JSONB),
    Column("version", BigInteger),
    Column("merged_into", String),
    Column("archived_at", DateTime(timezone=True)),
    Column("created_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True)),
    schema="ops",
)
topic_labels = Table(
    "analysis_topic_labels",
    metadata,
    Column("id", String),
    Column("normalized_name", String, primary_key=True),
    Column("is_canonical", Boolean),
    schema="ops",
)
candidates = Table(
    "analysis_topic_candidates",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("normalized_name", String),
    Column("name", String),
    Column("description", String),
    Column("promoted_topic_id", String),
    Column("created_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True)),
    schema="ops",
)
evidence = Table(
    "analysis_topic_evidence",
    metadata,
    Column("candidate_id", UUID(as_uuid=True)),
    Column("source", String),
    Column("source_id", String),
    Column("article_id", UUID(as_uuid=True)),
    Column("publisher", String),
    Column("quote", String),
    Column("created_at", DateTime(timezone=True)),
    schema="ops",
)
article_topics = Table(
    "analysis_article_topics",
    metadata,
    Column("source", String),
    Column("source_id", String),
    Column("article_id", UUID(as_uuid=True)),
    Column("topic_id", String),
    Column("origin", String),
    Column("created_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True)),
    schema="ops",
)
article_versions = Table(
    "analysis_article_versions",
    metadata,
    Column("source", String),
    Column("source_id", String),
    Column("article_id", UUID(as_uuid=True)),
    Column("content_hash", String),
    schema="ops",
)
topic_history = Table(
    "analysis_topic_history",
    metadata,
    Column("id", BigInteger, primary_key=True),
    Column("topic_id", String),
    Column("action", String),
    Column("detail", JSONB),
    Column("created_at", DateTime(timezone=True)),
    schema="ops",
)
article_topic_history = Table(
    "analysis_article_topic_history",
    metadata,
    Column("id", BigInteger, primary_key=True),
    Column("source", String),
    Column("source_id", String),
    Column("content_hash", String),
    Column("original_topic_id", String),
    Column("resulting_topic_id", String),
    Column("previous_origin", String),
    Column("resulting_origin", String),
    Column("action", String),
    Column("created_at", DateTime(timezone=True)),
    schema="ops",
)
analysis_runs = Table(
    "analysis_runs",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("article_id", UUID(as_uuid=True)),
    Column("source", String),
    Column("source_id", String),
    Column("content_hash", String),
    Column("model", String),
    Column("prompt", String),
    Column("prompt_hash", String),
    Column("status", String),
    Column("catalog_snapshot", JSONB),
    Column("model_draft", JSONB),
    Column("applied_result", JSONB),
    Column("usage", JSONB),
    Column("error", String),
    Column("lease_expires_at", DateTime(timezone=True)),
    Column("created_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True)),
    schema="ops",
)
analysis_attempts = Table(
    "analysis_attempts",
    metadata,
    Column("id", BigInteger, primary_key=True),
    Column("run_id", UUID(as_uuid=True)),
    Column("prefect_flow_run_id", UUID(as_uuid=True)),
    Column("prefect_task_run_id", UUID(as_uuid=True)),
    Column("model", String),
    Column("prompt", String),
    Column("prompt_hash", String),
    Column("status", String),
    Column("error", String),
    Column("usage", JSONB),
    Column("model_draft", JSONB),
    Column("started_at", DateTime(timezone=True)),
    Column("finished_at", DateTime(timezone=True)),
    schema="ops",
)
