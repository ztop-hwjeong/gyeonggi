-- 진행 중인 기사 저장 완료 후 언론사 기준 교체
LOCK TABLE dw.search_items, dw.news_items, dw.article_contents, dw.article_sources, dw.articles IN ACCESS EXCLUSIVE MODE;

CREATE TABLE dw.publisher_categories (
    code text PRIMARY KEY CHECK (btrim(code) <> ''),
    name text NOT NULL UNIQUE CHECK (btrim(name) <> '')
);
ALTER TABLE dw.publishers
    ADD COLUMN category_code text REFERENCES dw.publisher_categories(code) ON UPDATE CASCADE;
CREATE INDEX publishers_category_idx ON dw.publishers(category_code);
ALTER TABLE dw.publisher_domains
    ALTER COLUMN publisher_code DROP NOT NULL,
    ADD COLUMN evidence jsonb NOT NULL DEFAULT '{}';
CREATE TABLE dw.publisher_source_codes (
    source text NOT NULL CHECK (btrim(source) <> ''),
    source_code text NOT NULL CHECK (btrim(source_code) <> ''),
    PRIMARY KEY (source, source_code),
    publisher_code text NOT NULL REFERENCES dw.publishers(code) ON UPDATE CASCADE
);

CREATE OR REPLACE FUNCTION dw.resolve_publisher_code(identifier text) RETURNS text LANGUAGE sql AS $$
    SELECT coalesce(
        (SELECT publisher_code FROM dw.publisher_domains WHERE domain = identifier),
        (SELECT publisher_code FROM dw.publisher_source_codes
            WHERE source = 'naver' AND identifier = 'naver:' || source_code),
        (SELECT code FROM dw.publishers WHERE code = identifier AND category_code IS NOT NULL)
    );
$$;

CREATE FUNCTION dw.article_publisher_identifier(raw_url text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN dw.article_publisher_domain(raw_url) IN ('n.news.naver.com', 'news.naver.com')
        THEN 'naver:' || coalesce(substring(raw_url from '/article/([0-9]{3})/'), substring(raw_url from '[?&]oid=([0-9]{3})'))
        ELSE dw.article_publisher_domain(raw_url) END;
$$;

CREATE OR REPLACE FUNCTION dw.assign_search_publisher() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE resolved text; display_name text;
BEGIN
    IF NEW.provider <> 'naver' OR NEW.channel <> 'news' THEN RETURN NEW; END IF;
    resolved := dw.resolve_publisher_code(coalesce(
        dw.article_publisher_identifier(coalesce(nullif(NEW.data->>'original_url', ''), NEW.data->>'url')),
        NEW.data->>'publisher_domain', NEW.data->>'publisher_code'));
    SELECT name INTO display_name FROM dw.publishers WHERE code = resolved;
    NEW.data := NEW.data || jsonb_build_object(
        'publisher_code', resolved, 'publisher', coalesce(display_name, NEW.data->>'publisher'));
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION dw.sync_article_source_publisher() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE resolved text; display_name text;
BEGIN
    resolved := dw.resolve_publisher_code(dw.article_publisher_identifier(coalesce(nullif(NEW.original_url, ''), NEW.url)));
    IF resolved IS NOT NULL THEN
        SELECT name INTO display_name FROM dw.publishers WHERE code = resolved;
        UPDATE dw.articles SET publisher_code = resolved, publisher = coalesce(display_name, publisher)
        WHERE id = NEW.article_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION dw.sync_publisher_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE dw.articles SET publisher = NEW.name WHERE publisher_code = NEW.code;
    UPDATE dw.search_items SET data = data WHERE provider = 'naver' AND channel = 'news'
        AND dw.resolve_publisher_code(dw.article_publisher_identifier(
            coalesce(nullif(data->>'original_url', ''), data->>'url'))) = NEW.code;
    RETURN NEW;
END;
$$;

CREATE FUNCTION dw.sync_publisher_source_code() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE dw.search_items SET data = data WHERE provider = 'naver' AND channel = 'news'
        AND NEW.source = 'naver'
        AND dw.article_publisher_identifier(coalesce(nullif(data->>'original_url', ''), data->>'url')) = 'naver:' || NEW.source_code;
    RETURN NEW;
END;
$$;
CREATE TRIGGER sync_publisher_source_code AFTER INSERT OR UPDATE OF publisher_code ON dw.publisher_source_codes
FOR EACH ROW EXECUTE FUNCTION dw.sync_publisher_source_code();

