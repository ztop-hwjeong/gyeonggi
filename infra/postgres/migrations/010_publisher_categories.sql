CREATE TEMP TABLE publisher_remap ON COMMIT DROP AS
SELECT p.code AS identifier, coalesce(d.publisher_code, r.code) AS publisher_code
FROM previous_publishers p
LEFT JOIN verified_domains d ON d.domain = p.code
LEFT JOIN (
    SELECT name, min(code) AS code FROM reference_publishers GROUP BY name HAVING count(*) = 1
) r ON r.name = p.name
WHERE coalesce(d.publisher_code, r.code) IS NOT NULL
    AND p.code <> coalesce(d.publisher_code, r.code);

INSERT INTO dw.publisher_domains(domain, publisher_code, evidence)
SELECT domain, publisher_code, evidence FROM verified_domains
ON CONFLICT (domain) DO UPDATE SET publisher_code = EXCLUDED.publisher_code, evidence = EXCLUDED.evidence;

UPDATE dw.articles a SET publisher_code = r.publisher_code, publisher = p.name
FROM publisher_remap r JOIN dw.publishers p ON p.code = r.publisher_code
WHERE a.publisher_code = r.identifier;

-- 기준 목록 밖의 도메인 연결 해제와 수집 근거 보존
UPDATE dw.publisher_domains d
SET publisher_code = NULL,
    evidence = d.evidence || jsonb_build_object('method', 'not_in_reference', 'observed_name', p.name)
FROM previous_publishers p
WHERE d.publisher_code = p.code
    AND NOT EXISTS (SELECT 1 FROM reference_publishers r WHERE r.code = d.publisher_code);

UPDATE dw.articles a SET publisher_code = NULL
WHERE publisher_code IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM reference_publishers r WHERE r.code = a.publisher_code);

UPDATE dw.search_items SET data = data WHERE provider = 'naver' AND channel = 'news';

INSERT INTO dw.publisher_source_codes(source, source_code, publisher_code)
SELECT 'naver', coalesce(substring(s.url from '/article/([0-9]{3})/'), substring(s.url from '[?&]oid=([0-9]{3})')), min(d.publisher_code)
FROM dw.article_sources s
JOIN dw.publisher_domains d ON d.domain = dw.article_publisher_domain(s.original_url)
WHERE dw.article_publisher_domain(s.url) IN ('n.news.naver.com', 'news.naver.com')
    AND d.publisher_code IS NOT NULL
    AND coalesce(substring(s.url from '/article/([0-9]{3})/'), substring(s.url from '[?&]oid=([0-9]{3})')) IS NOT NULL
GROUP BY 2 HAVING count(DISTINCT d.publisher_code) = 1;

